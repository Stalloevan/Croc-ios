#!/usr/bin/env python3
"""Generates the crocodile glyph used by the app.

One outline (below) feeds both outputs so the icon and the in-app glyph always match:
  - CrocApp/CrocGlyph.swift  (SwiftUI Shape)
  - CrocApp/Assets.xcassets/AppIcon.appiconset/icon-1024.png
Run: python3 scripts/make_glyph.py   (needs Pillow)
"""
import os
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Right half of the outline, top (snout tip) to bottom (tail tip), in a 100x100 box.
HALF = [
    (50, 2), (54.5, 3), (56.5, 7), (57.5, 11), (58, 17), (58.5, 23), (61, 29), (63.5, 34), (64, 39), (62, 42.5),
    (66, 44), (73, 45), (79, 50), (81, 56), (77, 57.5), (73, 53), (66, 52.5),
    (62.5, 56), (62.5, 63),
    (66, 66), (73, 67), (78, 72), (79, 78), (75, 79), (71, 75), (64, 74),
    (61, 78), (58, 86), (54.5, 94), (50, 99.5),
]
EYES = [((57.2, 33.0), 1.7)]  # (center, radius) on the right; mirrored automatically


def outline():
    right = HALF
    left = [(100 - x, y) for (x, y) in reversed(HALF[1:-1])]
    return right + left  # closed loop


def bezier_segments(pts):
    """Closed Catmull-Rom -> cubic beziers: list of (p0, c1, c2, p1)."""
    n = len(pts)
    segs = []
    for i in range(n):
        p0, p1 = pts[i], pts[(i + 1) % n]
        pm, p2 = pts[(i - 1) % n], pts[(i + 2) % n]
        c1 = (p0[0] + (p1[0] - pm[0]) / 6, p0[1] + (p1[1] - pm[1]) / 6)
        c2 = (p1[0] - (p2[0] - p0[0]) / 6, p1[1] - (p2[1] - p0[1]) / 6)
        segs.append((p0, c1, c2, p1))
    return segs


def flatten(segs, steps=24):
    out = []
    for p0, c1, c2, p1 in segs:
        for s in range(steps):
            t = s / steps
            a, b, c, d = (1 - t) ** 3, 3 * (1 - t) ** 2 * t, 3 * (1 - t) * t * t, t ** 3
            out.append((a * p0[0] + b * c1[0] + c * c2[0] + d * p1[0],
                        a * p0[1] + b * c1[1] + c * c2[1] + d * p1[1]))
    return out


def write_swift(pts):
    f = lambda v: ("%.2f" % v).rstrip("0").rstrip(".")
    pt_lines = ",\n".join("        CGPoint(x: %s, y: %s)" % (f(x), f(y)) for x, y in pts)
    eyes = []
    for (cx, cy), r in EYES:
        eyes.append((cx, cy, r))
        eyes.append((100 - cx, cy, r))
    eye_lines = ",\n".join("        (%s, %s, %s)" % (f(x), f(y), f(r)) for x, y, r in eyes)
    src = f'''import SwiftUI

// Generated by scripts/make_glyph.py. Do not edit by hand.

/// The Croc glyph: a crocodile seen from above. Draws in a square; fill it with any color.
struct CrocGlyph: Shape {{
    private static let outline: [CGPoint] = [
{pt_lines}
    ]

    private static let eyes: [(Double, Double, Double)] = [
{eye_lines}
    ]

    func path(in rect: CGRect) -> Path {{
        let side = min(rect.width, rect.height)
        let scale = side / 100
        let origin = CGPoint(x: rect.midX - side / 2, y: rect.midY - side / 2)
        func map(_ p: CGPoint) -> CGPoint {{
            CGPoint(x: origin.x + p.x * scale, y: origin.y + p.y * scale)
        }}

        let pts = Self.outline
        let n = pts.count
        var path = Path()
        path.move(to: map(pts[0]))
        for i in 0..<n {{
            let p0 = pts[i], p1 = pts[(i + 1) % n]
            let pm = pts[(i + n - 1) % n], p2 = pts[(i + 2) % n]
            let c1 = CGPoint(x: p0.x + (p1.x - pm.x) / 6, y: p0.y + (p1.y - pm.y) / 6)
            let c2 = CGPoint(x: p1.x - (p2.x - p0.x) / 6, y: p1.y - (p2.y - p0.y) / 6)
            path.addCurve(to: map(p1), control1: map(c1), control2: map(c2))
        }}
        path.closeSubpath()

        // Eyes are cut out of the body (use even-odd fill, which CrocGlyphView does).
        for (x, y, r) in Self.eyes {{
            path.addEllipse(in: CGRect(x: origin.x + (x - r) * scale,
                                       y: origin.y + (y - r) * scale,
                                       width: 2 * r * scale, height: 2 * r * scale))
        }}
        return path
    }}
}}

/// Convenience: the glyph filled with the accent color (or any color).
struct CrocGlyphView: View {{
    var size: CGFloat = 56
    var color: Color = .accentColor

    var body: some View {{
        CrocGlyph()
            .fill(color, style: FillStyle(eoFill: true))
            .frame(width: size, height: size)
            .accessibilityHidden(true)
    }}
}}
'''
    open(os.path.join(ROOT, "CrocApp", "CrocGlyph.swift"), "w").write(src)


def render_icon(pts, path):
    S = 2048
    img = Image.new("RGB", (S, S))
    d = ImageDraw.Draw(img)
    top, bot = (10, 84, 56), (52, 199, 123)
    for y in range(S):
        t = y / (S - 1)
        d.line([(0, y), (S, y)], fill=tuple(int(top[i] + (bot[i] - top[i]) * t) for i in range(3)))

    size = 1280  # glyph box in px (on the 2048 canvas)
    ox = oy = (S - size) / 2
    poly = [(ox + x / 100 * size, oy + y / 100 * size) for x, y in flatten(bezier_segments(pts))]
    mask = Image.new("L", (S, S), 0)
    md = ImageDraw.Draw(mask)
    md.polygon(poly, fill=255)
    for (cx, cy), r in EYES:
        for ex in (cx, 100 - cx):
            X, Y, R = ox + ex / 100 * size, oy + cy / 100 * size, r / 100 * size
            md.ellipse([X - R, Y - R, X + R, Y + R], fill=0)

    shadow = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    shadow.putalpha(mask.point(lambda v: int(v * 0.30)))
    shadow = shadow.filter(ImageFilter.GaussianBlur(26))
    img.paste(Image.new("RGB", (S, S), (0, 40, 22)), (0, 24), shadow.split()[3])
    img.paste(Image.new("RGB", (S, S), (255, 252, 244)), (0, 0), mask)
    img.resize((1024, 1024), Image.LANCZOS).save(path)


if __name__ == "__main__":
    pts = outline()
    write_swift(pts)
    render_icon(pts, os.path.join(ROOT, "CrocApp", "Assets.xcassets", "AppIcon.appiconset", "icon-1024.png"))
    print("ok")
